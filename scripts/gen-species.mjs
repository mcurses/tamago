#!/usr/bin/env node
// Regenerates the species block in sidebar/tamago.swift from sidebar/species.json.
// The sidebar interpreter has no file access, so the art has to live in the .swift file itself.
// Frames are joined with "¶" and lines with "§"; raw strings (#"…"#) keep quotes and backslashes
// literal, which plain string literals in the interpreter don't.

import fs from "node:fs";
import path from "node:path";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const swiftFile = path.join(root, "sidebar/tamago.swift");
const data = JSON.parse(fs.readFileSync(path.join(root, "sidebar/species.json"), "utf8"));
const BEGIN = "// BEGIN species (generated by scripts/gen-species.mjs from sidebar/species.json; don't edit)";
const END = "// END species";

const names = Object.keys(data.species);
// A literal cmux(...) call per item: sidebar button actions must be the cmux call itself.
const request = (name) => `cmux("workspace.action", workspace_id: w.id, action: "set_description", description: "tamago:species:${name}")`;
const lines = [
  BEGIN,
  `// Art: ${data.source}`,
  `func speciesNames() -> String { return "${names.join("§")}" }`,
  "",
  "func speciesArt(_ s) -> String {",
  ...names.map((name) => {
    const art = data.species[name].map((frame) => frame.join("§")).join("¶");
    if (art.includes('"#')) throw new Error(`${name}: art contains the raw-string terminator`);
    return `    if s == "${name}" { return #"${art}"# }`;
  }),
  '    return ""',
  "}",
  "",
  "func speciesMenu(_ w) -> some View {",
  `    Button("Egg") { ${request("egg")} }`,
  "    Divider()",
  ...names.map((name) => `    Button("${name[0].toUpperCase() + name.slice(1)}") { ${request(name)} }`),
  "}",
  END,
];

const swift = fs.readFileSync(swiftFile, "utf8");
const start = swift.indexOf(BEGIN);
const end = swift.indexOf(END);
if (start < 0 || end < 0) throw new Error(`markers not found in ${swiftFile}`);
fs.writeFileSync(swiftFile, swift.slice(0, start) + lines.join("\n") + swift.slice(end + END.length));
console.log(`wrote ${names.length} species to ${path.relative(root, swiftFile)}`);
