#!/bin/zsh
# Writes extension/Meum/SpeciesArt.swift: sidebar/species.json as a string inside the meum widget's
# library. meum dlopens a copy of the library from a temporary folder, so a file next to the
# installed library can't be found from it. scripts/build-meum-widget.sh runs this; the generated
# file is checked in so a plain `swift build` works, and test/species-art.test.mjs keeps it current.
set -euo pipefail
ROOT=${0:A:h:h}
OUT=$ROOT/extension/Meum/SpeciesArt.swift
{
  print '// Generated by scripts/gen-species-swift.sh from sidebar/species.json. Do not edit.'
  print ''
  print 'let embeddedSpeciesJSON = ##"""'
  cat $ROOT/sidebar/species.json
  print '"""##'
} >$OUT.new
mv $OUT.new $OUT
